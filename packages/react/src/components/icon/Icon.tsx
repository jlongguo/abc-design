function toPascalCase(str: string): string {
  return str
    .split(/[-_]/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join('')
}

const customGlobalIcons: Record<string, AbcIconComponent> = {}

/** 全局注册自定义业务图标映射，供菜单路由配置按字符串名称动态解析 */
export function registerAbcIcons(icons: Record<string, AbcIconComponent>): void {
  Object.assign(customGlobalIcons, icons)
}

export interface IconProps {
  /** 图标注册名称（支持 Lucide 名、语义短名或 el-icon-* 历史名称） */
  name?: string
  /** 可选传入菜单文本用于智能语义推导最佳图标 */
  text?: string
  /** 像素尺寸 */
  size?: number | string
  /** 线条粗细 */
  strokeWidth?: number
  /** 自定义类名 */
  className?: string
  /** 局部注入的额外注册表 */
  registry?: Record<string, AbcIconComponent>
}

export const Icon: React.FC<IconProps> = ({
  name = '',
  text = '',
  size = 16,
  strokeWidth = 1.85,
  className,
  registry,
}) => {
  // 1. 若传入菜单文本，优先按语义关键词智能匹配
  if (text) {
    const textLower = text.toLowerCase()
    for (const rule of KEYWORD_ICON_RULES) {
      if (rule.keywords.some((kw) => textLower.includes(kw))) {
        const Matched = BUILTIN_ICONS[rule.iconName]
        if (Matched) {
          return <Matched size={size} strokeWidth={strokeWidth} className={cn('shrink-0', className)} />
        }
      }
    }
  }

  const rawClean = (name || '').replace(/^el-icon-/, '').trim()
  const cleanNoPrefix = rawClean.replace(/^s-/, '')
  const aliasedKey = ICON_ALIASES[rawClean] ?? ICON_ALIASES[cleanNoPrefix] ?? ICON_ALIASES[name]

  let Resolved: AbcIconComponent | undefined =
    registry?.[rawClean] ??
    customGlobalIcons[rawClean] ??
    (aliasedKey ? BUILTIN_ICONS[aliasedKey] : undefined) ??
    BUILTIN_ICONS[rawClean] ??
    (rawClean ? BUILTIN_ICONS[toPascalCase(rawClean)] : undefined)

  if (!Resolved && rawClean) {
    const lower = rawClean.toLowerCase()
    for (const rule of KEYWORD_ICON_RULES) {
      if (rule.keywords.some((kw) => lower.includes(kw))) {
        Resolved = BUILTIN_ICONS[rule.iconName]
        break
      }
    }
  }

  const FinalComp = Resolved ?? Compass
  return <FinalComp size={size} strokeWidth={strokeWidth} className={cn('shrink-0', className)} />
}

export default Icon
